// Generates src/styles/theme-tokens.css from kora_theme's theme.json, using the same derivation as kora_theme/theme.js
// (tokensFrom/shapeFrom). The web panel isn't a NUI page, so it can't load theme.js from cfx-nui; run `pnpm theme`
// after theme.json changes. Usage: node scripts/theme-tokens.mjs [path/to/theme.json]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ?? '/home/DevTestingKora/kora/server/txData/kora dev/resources/[standalone]/kora_theme/theme.json';
const theme = JSON.parse(fs.readFileSync(src, 'utf8'));
const number = (v) => (Number.isInteger(v) ? String(v) : String(Math.round(v * 10) / 10));
function hsl(hex, alpha, off = 0) {
  const r = parseInt(hex.slice(1, 3), 16) / 255, g = parseInt(hex.slice(3, 5), 16) / 255, b = parseInt(hex.slice(5, 7), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), d = max - min;
  let h = 0, s = 0, l = (max + min) / 2;
  if (d) {
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = (g - b) / d + (g < b ? 6 : 0); else if (max === g) h = (b - r) / d + 2; else h = (r - g) / d + 4;
    h /= 6;
  }
  l = Math.max(0, Math.min(100, l * 100 + off));
  const v = `${number(h * 360)} ${number(s * 100)}% ${number(l)}%`;
  return alpha == null ? v : `${v} / ${number(alpha)}`;
}
const lin = (v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const darkL = lin(16 / 255);
const lum = (hex) => 0.2126 * lin(parseInt(hex.slice(1, 3), 16) / 255) + 0.7152 * lin(parseInt(hex.slice(3, 5), 16) / 255) + 0.0722 * lin(parseInt(hex.slice(5, 7), 16) / 255);
const contrast = (hex) => { const v = lum(hex); return 1.05 / (v + 0.05) >= (v + 0.05) / (darkL + 0.05) ? '0 0% 100%' : '0 0% 6.3%'; };
const c = theme.colors;
const t = (role, a, o) => hsl(c[role], a, o);
const tokens = {
  background: t('background'), foreground: t('foreground'), card: t('surface'), 'card-foreground': t('foreground'), popover: t('surfacePopover'), 'popover-foreground': t('foreground'),
  secondary: t('surfaceRaised'), 'secondary-foreground': t('foreground'), muted: t('surfaceRaised'), 'muted-foreground': t('mutedForeground'), accent: t('surfaceHover'), 'accent-foreground': t('foreground'),
  border: t('border'), 'border-strong': t('borderStrong'), input: t('control'), 'control-border': t('control'), 'control-border-hover': t('controlHover'), 'surface-raised': t('surfaceRaised'), 'surface-hover': t('surfaceHover'),
  hud: t('surface', 0.72), 'modal-overlay': t('background', 0.68),
  primary: t('primary'), ring: t('primary'), 'focus-ring': t('primary', 0.55), selection: t('primary', 0.35), 'brand-hover': t('primary', null, -5.1), 'brand-pressed': t('primary', null, -10.6), 'brand-soft': t('primary', 0.14), 'brand-border': t('primary', 0.45), 'primary-foreground': contrast(c.primary),
  success: t('success'), 'success-soft': t('success', 0.14), 'success-border': t('success', 0.45), warning: t('warning'), 'warning-soft': t('warning', 0.14), 'warning-border': t('warning', 0.45),
  destructive: t('danger'), 'destructive-soft': t('danger', 0.14), 'destructive-border': t('danger', 0.45), 'destructive-foreground': contrast(c.danger),
  info: t('info'), 'info-soft': t('info', 0.14), 'info-border': t('info', 0.45), armour: t('armour'), 'armour-soft': t('armour', 0.14), 'armour-border': t('armour', 0.45),
};
const r = Math.max(0, Math.min(24, theme.shape?.radius ?? 8));
Object.assign(tokens, { radius: `${Math.round(r)}px`, 'radius-sm': `${Math.round(r * 0.75)}px`, 'radius-lg': `${Math.round(r * 1.25)}px` });
const shadows = theme.shape?.shadows === 'none'
  ? { 'shadow-low': '0 0 #0000', 'shadow-floating': '0 0 #0000', 'shadow-modal': '0 0 #0000' }
  : { 'shadow-low': '0 2px 8px rgb(0 0 0 / 24%)', 'shadow-floating': '0 10px 28px rgb(0 0 0 / 40%)', 'shadow-modal': '0 20px 56px rgb(0 0 0 / 50%)' };
Object.assign(tokens, shadows);
const out = `/* Generated by scripts/theme-tokens.mjs from kora_theme/theme.json (${theme.name}). Do not edit; run \`pnpm theme\`. */\n:root {\n${Object.entries(tokens).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}\n`;
fs.writeFileSync(path.join(here, '..', 'src', 'styles', 'theme-tokens.css'), out);
console.log(`wrote ${Object.keys(tokens).length} tokens`);
