// Teleport spots -> per-resource location aliases (tests/qa.lua).
// Mod-set spots (spots[testId], plus a test's own `tp`) win: when a test has any, its proposals are ignored.
// Proposals keep a `-- proposed, from <source>` comment in qa.lua.
const num = (v) => (Number.isFinite(Number(v)) ? Number(v) : null);

export function aliasName(label) {
  let s = String(label ?? 'spot').toLowerCase().replace(/&/g, ' and ').replace(/'/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  if (!s) s = 'spot';
  if (/^[0-9]/.test(s)) s = `at_${s}`;
  return s.slice(0, 48);
}

// Labels that don't name a place: the alias is named after the test instead.
export const GENERIC_LABEL = /^\s*(from the test( steps)?|test steps|spot|location|here|coords?|coordinates)\s*$/i;

const sameSpot = (a, b) => Math.abs(a.x - b.x) < 0.5 && Math.abs(a.y - b.y) < 0.5 && Math.abs(a.z - b.z) < 0.5;

// tests: normalised game tests (need .id, .resource, .tp). spots: { spots, proposals }.
// -> { byResource: { res: { name: {x,y,z,h?, label, proposed, sources:[], tests:[]} } }, byTest: { testId: [aliasName] } }
export function buildLocationAliases(tests, spots) {
  const byResource = {};
  const byTest = {};
  const renames = {}; // res -> { oldGenericName: newName } (old = what a label-only name would have been)
  for (const t of tests) {
    const own = [...(t.tp ?? []), ...(spots.spots?.[t.id] ?? [])].map((s) => ({ ...s, proposed: false }));
    const list = own.length ? own : (spots.proposals?.[t.id] ?? []).map((s) => ({ ...s, proposed: true }));
    for (const s of list) {
      const x = num(s.x), y = num(s.y), z = num(s.z);
      if (x === null || y === null || z === null) continue;
      const res = (byResource[t.resource] ??= {});
      const spot = { x, y, z, ...(num(s.h) !== null ? { h: num(s.h) } : {}) };
      let name = Object.keys(res).find((n) => sameSpot(res[n], spot));
      if (name) {
        // a Mod-confirmed use of the same coordinates upgrades the alias
        if (!s.proposed) res[name].proposed = false;
      } else {
        const generic = GENERIC_LABEL.test(String(s.label ?? ''));
        const base = generic ? aliasName(t.id) : aliasName(s.label);
        name = base;
        for (let i = 2; res[name]; i++) name = `${base}_${i}`;
        res[name] = { ...spot, label: generic ? `${t.id} (${s.label})` : String(s.label ?? name), proposed: !!s.proposed, sources: [], tests: [] };
        if (generic) (renames[t.resource] ??= {})[aliasName(s.label)] = name;
      }
      if (s.source && !res[name].sources.includes(s.source)) res[name].sources.push(String(s.source));
      if (!res[name].tests.includes(t.id)) res[name].tests.push(t.id);
      (byTest[t.id] ??= []).includes(name) || byTest[t.id].push(name);
    }
  }
  return { byResource, byTest, renames };
}

const luaNum = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const luaStr = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, ' ')}'`;

// One resource's qa.lua text. Returns plain tables only (qa.lua runs sandboxed).
export function renderQaLua(resource, locations, { header = true } = {}) {
  const lines = [];
  if (header) {
    lines.push(`-- ${resource} test aliases. Generated by kora-qa-panel/scripts/convert-legacy.mjs from communitybot`);
    lines.push('-- data/test-spots.json (Mod-set spots win over script proposals). Review before applying.');
  }
  lines.push('return {', '    locations = {');
  for (const name of Object.keys(locations).sort()) {
    const l = locations[name];
    const why = `${l.label}; used by ${l.tests.join(', ')}`;
    if (l.proposed) lines.push(`        -- proposed, from ${l.sources.length ? l.sources.join(', ') : 'script proposal'} (${why})`);
    else lines.push(`        -- ${why}`);
    const h = l.h !== undefined ? `, h = ${luaNum(l.h)}` : '';
    lines.push(`        ${/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : `[${luaStr(name)}]`} = { x = ${luaNum(l.x)}, y = ${luaNum(l.y)}, z = ${luaNum(l.z)}${h} },`);
  }
  lines.push('    },', '}', '');
  return lines.join('\n');
}
